    val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.ENGLISH }

    fun getText(key: AppTextKey, language: AppLanguage): String {
        return translationsByLanguage[language]?.get(key)
            ?: english[key]
            ?: key.id
    }

    @Composable
    fun text(key: AppTextKey): String {
        return getText(key, LocalAppLanguage.current)
    }
}

/**
 * Arabic uses RTL. Everything else stays LTR.
 */
fun layoutDirectionFor(language: AppLanguage): LayoutDirection {
    return if (language == AppLanguage.ARABIC) LayoutDirection.Rtl else LayoutDirection.Ltr
}

